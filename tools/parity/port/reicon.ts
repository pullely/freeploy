// Generate apps/deploy-web/src/components/generated/reicon-paths.ts from
// Coolify's resources/views/components/reicon.blade.php: the icon name → SVG
// inner markup map, verbatim (DP3).
//
//   node tools/parity/port/reicon.ts --coolify <coolify checkout> --out <file>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2);
const opt = (k: string) => args[args.indexOf(`--${k}`) + 1]!;
const src = readFileSync(join(opt("coolify"), "resources/views/components/reicon.blade.php"), "utf8");
const icons: Record<string, string> = {};
for (const m of src.matchAll(/^\s*'([\w-]+)' => '((?:\\'|[^'])*)',\s*$/gm)) icons[m[1]!] = m[2]!.replace(/\\'/g, "'");
const out = `// GENERATED by tools/parity/port/reicon.ts — do not edit.
// Derived from coollabsio/coolify@91b7e3e:resources/views/components/reicon.blade.php (Apache-2.0).
// Coolify's icon glyphs (reicon outline pack), name → inner SVG markup.
export const REICON_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(icons, null, 2)};
`;
writeFileSync(opt("out"), out);
console.log(`${Object.keys(icons).length} icons`);
