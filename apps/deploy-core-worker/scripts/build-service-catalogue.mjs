// Builds the service template catalogue Freeploy ships (src/services/catalogue-data.ts) from a checkout of
// coollabsio/coolify, the way Coolify's own `php artisan generate:services` builds
// templates/service-templates-latest.json. The generator itself is src/services/catalogue-build.ts.
//
//   node scripts/build-service-catalogue.mjs <coolify checkout> [--fixture <templates.json.gz>]
//
// `template_last_updated_at` is `git log -1 --format=%cI -- templates/compose/<file>` in that checkout,
// as in Coolify. A shallow clone has no history to ask, so there the date is taken from Coolify's own
// committed catalogue when it has the same Compose text for the template, and is null otherwise.
//
// --fixture also writes the template files themselves, gzipped, for the tests
// (tests/deploy-core-worker/fixtures/compose-yaml/templates.json.gz).
//
// Needs Node 22.18 or later (it runs the TypeScript sources directly).
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

// The sources import each other as "./x.js" (the bundler's convention); point those at the .ts files.
register(
  `data:text/javascript,${encodeURIComponent(
    'export async function resolve(specifier, context, next) { if (specifier.startsWith(".") && specifier.endsWith(".js") && context.parentURL?.endsWith(".ts")) { return next(specifier.slice(0, -3) + ".ts", context); } return next(specifier, context); }',
  )}`,
);

const here = dirname(fileURLToPath(import.meta.url));
const { buildCatalogue, catalogueJson, processTemplateFile } = await import("../src/services/catalogue-build.ts");

const [root, ...rest] = process.argv.slice(2);
if (!root) {
  console.error("usage: node scripts/build-service-catalogue.mjs <coolify checkout> [--fixture <templates.json.gz>]");
  process.exit(2);
}
const fixture = rest[0] === "--fixture" ? rest[1] : undefined;

const composeDir = join(root, "templates", "compose");
const templates = {};
for (const file of readdirSync(composeDir).sort()) templates[file] = readFileSync(join(composeDir, file), "utf8");

const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
const shallow = git("rev-parse", "--is-shallow-repository") === "true";
const committed = JSON.parse(readFileSync(join(root, "templates", "service-templates-latest.json"), "utf8"));

const dates = {};
let fromGit = 0;
let fromCommitted = 0;
let withoutDate = 0;
for (const file of Object.keys(templates)) {
  if (!/\.ya?ml$/.test(file)) continue;
  if (!shallow) {
    dates[file] = git("log", "-1", "--format=%cI", "--", `templates/compose/${file}`) || null;
    fromGit += 1;
    continue;
  }
  const processed = processTemplateFile(file, templates[file], null, templates);
  if (!processed) continue;
  const known = committed[processed.name];
  if (known && known.compose === processed.entry.compose && typeof known.template_last_updated_at === "string") {
    dates[file] = known.template_last_updated_at;
    fromCommitted += 1;
  } else {
    dates[file] = null;
    withoutDate += 1;
  }
}

const catalogue = buildCatalogue(templates, dates);
const json = catalogueJson(catalogue);
// Shipped as a module holding the JSON text: it is parsed on first use, and its bytes can be compared.
writeFileSync(
  join(here, "..", "src", "services", "catalogue-data.ts"),
  `// Generated by scripts/build-service-catalogue.mjs from coollabsio/coolify@${git("rev-parse", "--short", "HEAD")}:templates/compose (Apache-2.0).\n// Do not edit: run the script again. The text is what Coolify's generate:services writes.\nexport const CATALOGUE_JSON: string = ${JSON.stringify(json)};\n`,
);

const names = Object.keys(catalogue);
const same = names.filter((name) => JSON.stringify(catalogue[name]) === JSON.stringify(committed[name]));
const changed = names.filter((name) => committed[name] && JSON.stringify(catalogue[name]) !== JSON.stringify(committed[name]));
const added = names.filter((name) => !committed[name]);
const removed = Object.keys(committed).filter((name) => !catalogue[name]);
console.log(`coolify ${git("rev-parse", "--short", "HEAD")}${shallow ? " (shallow clone)" : ""}`);
console.log(`${Object.keys(templates).length} template files, ${names.length} catalogue entries, ${json.length} bytes`);
console.log(`dates: ${fromGit} from git, ${fromCommitted} from Coolify's committed catalogue, ${withoutDate} null`);
console.log(`against Coolify's committed service-templates-latest.json: ${same.length} entries identical, ${changed.length} differ (${changed.join(", ")}), ${added.length} only here (${added.join(", ")}), ${removed.length} only there (${removed.join(", ")})`);
console.log(json === readFileSync(join(root, "templates", "service-templates-latest.json"), "utf8") ? "byte-equal to Coolify's committed file" : "not byte-equal to Coolify's committed file (it is older than its templates)");

if (fixture) {
  const sorted = Object.fromEntries(Object.keys(templates).sort().map((file) => [file, templates[file]]));
  writeFileSync(fixture, gzipSync(Buffer.from(JSON.stringify(sorted), "utf8"), { level: 9 }));
  console.log(`wrote ${fixture}`);
}
