// Derived from coollabsio/coolify@91b7e3e:database/migrations/** (Apache-2.0), modified.
//
// Generates packages/db/src/migrations/500_deploy_core/up.sql — the `deploy`
// schema — from the folded final schema in
// specs/epics/freeploy-coolify-parity/parity/migrations.json (DP2).
//
// Rules (design.md §1.1):
//   * same table and column names as Coolify; Laravel's pgsql grammar for types
//     (Coolify runs on Postgres too, so this is its own physical schema)
//   * team_id → org_id UUID NOT NULL; every table gets org_id (risks DP-I)
//   * Lumen owns identity/membership/billing/events/sessions: those tables are
//     not created here (risks DP-J)
//   * tenancy enforced by Postgres: RLS enabled and FORCED on every table,
//     policy org_id = current_setting('deploy.org_id'); the worker runs every
//     transaction as role deploy_app, which cannot bypass RLS
//   * foreign keys between deploy tables are kept as plain bigint columns with
//     an index (Coolify's constrained() FKs reference tables Lumen owns for a
//     few of them; integrity inside deploy is enforced by the ported write paths)
//
//   node packages/db/scripts/generate-deploy-schema.ts [--check]
