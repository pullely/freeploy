// Derived from coollabsio/coolify@91b7e3e:database/migrations/** (Apache-2.0), modified.
//
// Generates packages/db/src/migrations/500_deploy_core/up.sql — the `deploy`
// schema — from the folded final schema in
// specs/epics/freeploy-coolify-parity/parity/migrations.json (DP2).
//
// Rules (design.md §1.1):
//   * same table and column names as Coolify; Laravel's pgsql grammar for types
//     (Coolify runs on Postgres too, so this is its own physical schema)
//   * team_id → org_id UUID NOT NULL; every table gets org_id (risks DP-I)
//   * Lumen owns identity/membership/billing/events/sessions: those tables are
//     not created here (risks DP-J)
//   * tenancy enforced by Postgres: RLS enabled and FORCED on every table,
//     policy org_id = current_setting('deploy.org_id'); the worker runs every
//     transaction as role deploy_app, which cannot bypass RLS
//   * foreign keys between deploy tables are kept as plain bigint columns with
//     an index (Coolify's constrained() FKs reference tables Lumen owns for a
//     few of them; integrity inside deploy is enforced by the ported write paths)
//
//   node packages/db/scripts/generate-deploy-schema.ts [--check]
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const inventory = JSON.parse(readFileSync(join(root, "specs/epics/freeploy-coolify-parity/parity/migrations.json"), "utf8"));
const out = join(root, "packages/db/src/migrations/500_deploy_core/up.sql");

/** Tables Lumen's own bounded contexts own (risks DP-J). */
export const LUMEN_OWNED = new Set([
  "users", "teams", "team_user", "team_invitations", "sessions", "password_reset_tokens",
  "personal_access_tokens", "subscriptions", "audit_events", "passkeys", "oauth_identities",
  "failed_jobs", "user_changelog_reads",
]);

interface Call { method: string; args: string[] }
interface Column { name: string; type: string; args: string[]; chain: Call[] }

/** Laravel's PostgresGrammar wraps every identifier in double quotes; so do we (Coolify has columns named "order", "commit", …). */
const q = (id: string) => `"${id.replace(/"/g, '""')}"`;
const has = (c: Column, m: string) => c.chain.some((x) => x.method === m);
const arg = (c: Column, m: string) => c.chain.find((x) => x.method === m)?.args[0];

/** Laravel's PostgresGrammar type for a Blueprint column. */
export function pgType(c: Column): string {
  const n = (i: number, d: number) => (c.args[i] && /^\d+$/.test(c.args[i]) ? Number(c.args[i]) : d);
  switch (c.type) {
    case "id": case "bigIncrements": return "BIGINT GENERATED BY DEFAULT AS IDENTITY";
    case "increments": return "INTEGER GENERATED BY DEFAULT AS IDENTITY";
    case "string": case "char": return `${c.type === "char" ? "CHAR" : "VARCHAR"}(${n(1, 255)})`;
    case "text": case "mediumText": case "longText": case "tinyText": return "TEXT";
    case "boolean": return "BOOLEAN";
    case "integer": case "unsignedInteger": return "INTEGER";
    case "smallInteger": case "unsignedSmallInteger": case "tinyInteger": case "unsignedTinyInteger": return "SMALLINT";
    case "bigInteger": case "unsignedBigInteger": case "foreignId": case "foreignIdFor": return "BIGINT";
    case "decimal": return `DECIMAL(${n(1, 8)}, ${n(2, 2)})`;
    case "float": case "double": return "DOUBLE PRECISION";
    case "json": case "schemalessAttributes": return "JSON";
    case "jsonb": return "JSONB";
    case "date": return "DATE";
    case "timestamp": case "dateTime": return `TIMESTAMP(${n(1, 0)}) WITHOUT TIME ZONE`;
    case "timestampTz": case "dateTimeTz": return `TIMESTAMP(${n(1, 0)}) WITH TIME ZONE`;
    case "time": return "TIME(0) WITHOUT TIME ZONE";
    case "uuid": return "UUID";
    case "enum": return "VARCHAR(255)";
    case "ipAddress": return "INET";
    case "binary": return "BYTEA";
    default: throw new Error(`no Postgres type for Blueprint ${c.type} (${c.name})`);
  }
}

/** A PHP default literal as SQL. */
export function pgDefault(raw: string, c: Column): string {
  const v = raw.trim();
  if (/^(true|false)$/i.test(v)) return v.toLowerCase();
  if (/^-?\d+(\.\d+)?$/.test(v)) return c.type === "boolean" ? (v === "0" ? "false" : "true") : v;
  if (/^null$/i.test(v)) return "NULL";
  const s = v.match(/^(['"])([\s\S]*)\1$/);
  if (s) return `'${s[2].replace(/\\(['"\\])/g, "$1").replace(/'/g, "''")}'`;
  const raw2 = v.match(/^(?:DB::raw|new\s+Expression)\(\s*(['"])([\s\S]*)\1\s*\)$/);
  if (raw2) return raw2[2];
  if (/^\[\s*\]$/.test(v)) return "'[]'";
  // Laravel's now() as a column default is the moment the migration ran in
  // Coolify (a constant); Postgres's CURRENT_TIMESTAMP is the same intent for
  // rows created later, which is how Coolify's code relies on it.
  if (/^now\(\)$/.test(v)) return "CURRENT_TIMESTAMP";
  // PHP backed-enum cases used as defaults, resolved from app/Enums at the pin.
  const ENUMS: Record<string, string> = { "ServerRole::BOTH->value": "'both'" };
  if (ENUMS[v]) return ENUMS[v];
  throw new Error(`cannot translate default ${v} on ${c.name}`);
}

export function enumCheck(table: string, c: Column): string | null {
  if (c.type !== "enum") return null;
  const values = [...(c.args[1] ?? "").matchAll(/(['"])(.*?)\1/g)].map((m) => `'${m[2].replace(/'/g, "''")}'`);
  return values.length ? `CONSTRAINT ${table}_${c.name}_check CHECK (${q(c.name)} IN (${values.join(", ")}))` : null;
}

export function tableSql(table: string, columns: Column[]): string {
  const cols: string[] = [];
  const extra: string[] = [];
  let hasId = false;
  for (const c of columns) {
    if (c.name === "team_id") continue; // becomes org_id below
    const isId = ["id", "bigIncrements", "increments"].includes(c.type);
    hasId ||= isId;
    let def = `  ${q(c.name)} ${pgType(c)}`;
    if (isId) def += " PRIMARY KEY";
    else {
      if (!has(c, "nullable")) def += " NOT NULL";
      const d = arg(c, "default");
      if (d !== undefined) def += ` DEFAULT ${pgDefault(d, c)}`;
      else if (has(c, "useCurrent")) def += " DEFAULT CURRENT_TIMESTAMP";
    }
    cols.push(def);
    const chk = enumCheck(table, c);
    if (chk) extra.push(`  ${chk}`);
  }
  cols.push("  org_id UUID NOT NULL");
  const lines = [`CREATE TABLE IF NOT EXISTS deploy.${table} (`, [...cols, ...extra].join(",\n"), ");"];
  lines.push(`COMMENT ON COLUMN deploy.${table}.org_id IS 'Owning Lumen organization (Coolify team_id). Enforced by RLS.';`);
  lines.push(`CREATE INDEX IF NOT EXISTS ${table}_org_id_idx ON deploy.${table} (org_id);`);
  for (const c0 of columns) {
    // An index or uniqueness on team_id is one on org_id (e.g. one notification-settings row per team).
    const c = c0.name === "team_id" ? { ...c0, name: "org_id" } : c0;
    if (c0.name === "team_id" && !has(c0, "unique")) continue; // org_id is already indexed
    if (c.name === "uuid" || has(c, "unique")) lines.push(`CREATE UNIQUE INDEX IF NOT EXISTS ${table}_${c.name}_unique ON deploy.${table} (${q(c.name)});`);
    else if (c.type === "foreignId" || has(c, "index") || has(c, "constrained")) lines.push(`CREATE INDEX IF NOT EXISTS ${table}_${c.name}_idx ON deploy.${table} (${q(c.name)});`);
  }
  lines.push(`ALTER TABLE deploy.${table} ENABLE ROW LEVEL SECURITY;`);
  lines.push(`ALTER TABLE deploy.${table} FORCE ROW LEVEL SECURITY;`);
  lines.push(`DROP POLICY IF EXISTS tenant_isolation ON deploy.${table};`);
  lines.push(`CREATE POLICY tenant_isolation ON deploy.${table} USING (org_id = deploy.current_org() OR deploy.is_platform_admin()) WITH CHECK (org_id = deploy.current_org() OR deploy.is_platform_admin());`);
  if (!hasId) lines.push(`-- no id column in Coolify (pivot table); none added`);
  return lines.join("\n");
}

export function generate(): { sql: string; tables: string[] } {
  const rows = inventory.rows.filter((r: { table: string }) => !LUMEN_OWNED.has(r.table));
  const header = `-- 500_deploy_core
-- GENERATED by packages/db/scripts/generate-deploy-schema.ts from
-- specs/epics/freeploy-coolify-parity/parity/migrations.json — do not edit by hand.
-- Derived from coollabsio/coolify@${inventory.coolifyRef}:database/migrations/** (Apache-2.0), modified:
-- team_id → org_id UUID, org_id on every table, row-level security on every table.
-- Bounded context: deploy

CREATE SCHEMA IF NOT EXISTS deploy;
COMMENT ON SCHEMA deploy IS 'Deploy bounded context — the Coolify resource model, one org per row, RLS-enforced.';

-- The role every deploy-core-worker transaction runs as (SET LOCAL ROLE).
-- NOLOGIN, NOBYPASSRLS: tenancy cannot be skipped by a query that forgets it.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'deploy_app') THEN
    CREATE ROLE deploy_app NOLOGIN NOBYPASSRLS;
  END IF;
END $$;
GRANT deploy_app TO CURRENT_USER;
GRANT USAGE ON SCHEMA deploy TO deploy_app;

-- The org the current transaction acts for: SET LOCAL deploy.org_id = '<uuid>'.
-- No org set → NULL → no row matches, nothing can be written.
CREATE OR REPLACE FUNCTION deploy.current_org() RETURNS UUID LANGUAGE sql STABLE AS
$fn$ SELECT NULLIF(current_setting('deploy.org_id', true), '')::uuid $fn$;
-- The Lumen operator (platform admin, DP12): SET LOCAL deploy.platform_admin = 'on'.
-- Only deploy-core-worker's platform-admin routes, after policy-worker allows it, set this.
CREATE OR REPLACE FUNCTION deploy.is_platform_admin() RETURNS BOOLEAN LANGUAGE sql STABLE AS
$fn$ SELECT coalesce(current_setting('deploy.platform_admin', true), '') = 'on' $fn$;
`;
  const tables: string[] = [];
  const body = rows.map((r: { table: string; columns: Column[] }) => {
    tables.push(r.table);
    return `-- ${r.table} (Coolify: ${r.columns.length} columns)\n${tableSql(r.table, r.columns)}`;
  });
  const grants = `
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA deploy TO deploy_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA deploy TO deploy_app;
`;
  return { sql: [header, ...body, grants].join("\n\n"), tables };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { sql, tables } = generate();
  if (process.argv.includes("--check")) {
    const current = readFileSync(out, "utf8");
    if (current !== sql) {
      console.error("500_deploy_core/up.sql is not what the generator produces; re-run it");
      process.exit(1);
    }
    console.log(`up to date: ${tables.length} tables`);
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, sql);
    console.log(`wrote ${tables.length} tables, sha256 ${createHash("sha256").update(sql).digest("hex")}`);
  }
}
